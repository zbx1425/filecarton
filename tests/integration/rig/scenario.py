"""Build a scenario PHP file of define() calls and the temp roots it points at."""

from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path

PASSWORD = "test-pass"
OUTSIDE_SENTINEL = "FC_OUTSIDE_SENTINEL_9f3a"
BOB_SENTINEL = "FC_BOB_SENTINEL_9f3a"
ALICE_MARKER = "hello from alice"

_HASH: str | None = None


def password_hash(php_exe: str, password: str = PASSWORD) -> str:
    global _HASH
    if _HASH is not None and password == PASSWORD:
        return _HASH
    env = dict(**{k: v for k, v in __import__("os").environ.items()})
    env["FC_PW"] = password
    result = subprocess.run(
        [php_exe, "-r", "echo password_hash(getenv('FC_PW'), PASSWORD_DEFAULT);"],
        capture_output=True,
        text=True,
        env=env,
        check=True,
    )
    digest = result.stdout.strip()
    if not digest.startswith("$"):
        raise RuntimeError(f"password_hash failed: {result.stderr}")
    if password == PASSWORD:
        _HASH = digest
    return digest


def php_literal(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, int) and not isinstance(value, bool):
        return str(value)
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(value, (list, tuple)):
        inner = ", ".join(php_literal(v) for v in value)
        return "[" + inner + "]"
    if isinstance(value, dict):
        parts = []
        for key, item in value.items():
            parts.append(php_literal(key) + " => " + php_literal(item))
        return "[" + ", ".join(parts) + "]"
    raise TypeError(type(value))


def fwd(path: Path | str) -> str:
    return str(path).replace("\\", "/")


@dataclass
class Scenario:
    work: Path
    php_file: Path
    front: str = "scenario"
    embed_base: Path | None = None
    idp: str = ""
    alice_root: Path | None = None
    bob_root: Path | None = None
    outside: Path | None = None
    sentinels: list[str] = field(default_factory=list)


def _write_defines(path: Path, defines: dict) -> None:
    lines = ["<?php", "// Generated by the integration rig. One scenario per worker pool."]
    for key, value in defines.items():
        lines.append(f"define({php_literal(key)}, {php_literal(value)});")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def _base_defines(extra: dict | None = None) -> dict:
    defines = {
        "FILECARTON_DEV_SERVER": "http://127.0.0.1:9",
        "FILECARTON_REPO_SETTING": {
            "rootPath": "",
            "readonly": False,
            "branding": "FileCarton",
            "repoName": "test",
            "featureArchive": True,
        },
        "FILECARTON_GRANT_RESOLVERS": [
            {"class": r"\FileCarton\StaticGrantResolver"},
        ],
    }
    if extra:
        defines.update(extra)
    return defines


def _plant(root: Path, name: str, content: str) -> None:
    root.mkdir(parents=True, exist_ok=True)
    (root / name).write_text(content, encoding="utf-8")


def two_users(work: Path, php_exe: str) -> Scenario:
    alice = work / "alice"
    bob = work / "bob"
    outside = work / "outside"
    _plant(alice, "hello.txt", ALICE_MARKER)
    _plant(bob, "secret.txt", BOB_SENTINEL)
    _plant(outside, "secret.txt", OUTSIDE_SENTINEL)
    hidden = alice / "hidden.txt"
    hidden.write_text("hidden-sentinel", encoding="utf-8")
    (alice / "shell.php").write_text("<?php echo 1;\n", encoding="utf-8")
    digest = password_hash(php_exe)
    users = [
        {"id": "alice", "passwordHash": digest, "root": fwd(alice)},
        {"id": "bob", "passwordHash": digest, "root": fwd(bob), "readonly": True},
    ]
    defines = _base_defines({
        "FILECARTON_STATIC_USER_LIST": users,
        "FILECARTON_AUTH_PROVIDERS": [
            {
                "class": r"\FileCarton\StaticPasswordAuth",
                "users": {"alice": digest, "bob": digest, "carol": digest},
            },
        ],
        "FILECARTON_IGNORE_REALPATH": [fwd(hidden.resolve())],
    })
    php_file = work / "scenario.php"
    _write_defines(php_file, defines)
    return Scenario(
        work=work,
        php_file=php_file,
        alice_root=alice,
        bob_root=bob,
        outside=outside,
        sentinels=[OUTSIDE_SENTINEL, BOB_SENTINEL],
    )


