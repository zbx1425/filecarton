def embed_state(work: Path) -> Scenario:
    base = work / "repos"
    photos = base / "photos"
    outside = work / "outside"
    _plant(photos, "pic.txt", "photo-bytes")
    _plant(outside, "secret.txt", OUTSIDE_SENTINEL)
    # scenario.php is unused in embed-front mode, but the pool still wants a path.
    php_file = work / "scenario.php"
    php_file.write_text("<?php\n", encoding="utf-8")
    return Scenario(
        work=work,
        php_file=php_file,
        front="embed",
        embed_base=base,
        alice_root=photos,
        outside=outside,
        sentinels=[OUTSIDE_SENTINEL],
    )


